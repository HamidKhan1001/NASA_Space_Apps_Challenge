#!/usr/bin/env python3
"""Bundle /data and strings.json into site/js/data-snapshot.js for the offline demo.

The site only loads this file when a data fetch fails (dead Wi-Fi, file:// URL),
so it costs nothing on the normal 3G path. Regenerate after every build_series run:
    python3 pipeline/make_snapshot.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "..", "data")
OUT = os.path.join(HERE, "..", "site", "js", "data-snapshot.js")


def main():
    bundle = {}
    for root, _, files in os.walk(DATA):
        for name in files:
            path = os.path.join(root, name)
            rel = os.path.relpath(path, DATA).replace(os.sep, "/")
            with open(path, encoding="utf-8") as fh:
                bundle[rel] = json.load(fh) if name.endswith((".json", ".geojson")) else fh.read()
    with open(os.path.join(HERE, "..", "site", "strings.json"), encoding="utf-8") as fh:
        bundle["strings.json"] = json.load(fh)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("/* generated by pipeline/make_snapshot.py; offline fallback only */\n")
        fh.write("window.ATLAS_SNAPSHOT=")
        json.dump(bundle, fh, ensure_ascii=False, separators=(",", ":"))
        fh.write(";\n")
    print(f"snapshot: {len(bundle)} files, {os.path.getsize(OUT)/1e6:.2f} MB -> {OUT}")


if __name__ == "__main__":
    main()
